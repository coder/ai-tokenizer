/**
 * Writes src/claude/unicode.ts, src/encoding/claude_v3.ts and
 * src/encoding/claude_v4_7.ts from ctok at CTOK_COMMIT. Needs `uv`.
 *
 *   bun scripts/generate-claude-encodings.ts
 *
 * A rerun on the same pin writes byte-identical files.
 */
import { writeFileSync } from "node:fs";
import * as prettier from "prettier";
import { CTOK_COMMIT, CTOK_REGEX, CTOK_REPO } from "./ctok";

const ENCODINGS = [
  {
    name: "claude_v3",
    ctok: "3.0",
    models: "Claude 3 through Claude Opus 4.6",
    // ctok's frame tail: the frame's own two newlines join a content-final run.
    tailNewlines: 2,
  },
  {
    name: "claude_v4_7",
    ctok: "4.8",
    models: "Claude Opus 4.7 and later (ctok --version 4.8)",
    // Measured on the Opus 4.8+ frame: the run tiles alone. ctok adds 2 here.
    tailNewlines: 0,
  },
] as const;

interface Family {
  family: string;
  foldQuotes: boolean;
  allcapsMin: number | null;
  frameBow: boolean;
  pieces: string[];
  bytePrefixes: string[];
  maxPieceLength: number;
}

interface Export {
  ctok: { version: string; commit: string };
  unicode: {
    version: string;
    classes: Record<string, number>;
    flags: Record<string, number>;
    facts: number[];
    lower: number[];
    assigned: number[];
    ccc: number[];
  };
  escape: number[];
  families: Record<string, Family>;
}

const proc = Bun.spawnSync(
  [
    "uv",
    "run",
    "--quiet",
    "--no-project",
    "--python",
    "3.13",
    "--with",
    `ctok @ git+${CTOK_REPO}@${CTOK_COMMIT}`,
    "--with",
    `regex==${CTOK_REGEX}`,
    "python",
    new URL("./ctok-export.py", import.meta.url).pathname,
    "--commit",
    CTOK_COMMIT,
    ...ENCODINGS.map((e) => e.ctok),
  ],
  { stdout: "pipe", stderr: "inherit" }
);
if (proc.exitCode !== 0) throw new Error(`ctok-export exited ${proc.exitCode}`);
const data = JSON.parse(proc.stdout.toString()) as Export;

const escape = new Set(data.escape);
const hex = (cp: number) => cp.toString(16).toUpperCase().padStart(4, "0");

/** A string literal with every invisible or marker codepoint escaped. */
function literal(s: string): string {
  let out = '"';
  for (const ch of s) {
    const cp = ch.codePointAt(0)!;
    if (ch === '"' || ch === "\\") out += "\\" + ch;
    else if (ch === "\n") out += "\\n";
    else if (ch === "\t") out += "\\t";
    else if (escape.has(cp)) {
      out += cp > 0xffff ? `\\u{${hex(cp)}}` : `\\u${hex(cp)}`;
    } else {
      if (
        cp < 0x20 ||
        (cp >= 0x7f && cp <= 0x9f) ||
        (cp >= 0xd800 && cp <= 0xdfff)
      ) {
        throw new Error(
          `unescaped control U+${hex(cp)} in ${JSON.stringify(s)}`
        );
      }
      out += ch;
    }
  }
  return out + '"';
}

const credit = (family?: string) =>
  ` * Ported from ctok ${data.ctok.version} (${CTOK_REPO}, commit\n` +
  ` * ${data.ctok.commit})${family ? `, family "${family}"` : ""}.\n` +
  ` * ctok is MIT licensed, Copyright (c) 2026 Sander Land.\n`;

const config = await prettier.resolveConfig(
  new URL("../src/index.ts", import.meta.url).pathname
);

async function write(path: string, source: string): Promise<void> {
  const formatted = await prettier.format(source, {
    ...config,
    parser: "typescript",
  });
  writeFileSync(new URL(`../${path}`, import.meta.url), formatted);
  console.log(`${path}: ${formatted.length.toLocaleString("en-US")} chars`);
}

const u = data.unicode;
await write(
  "src/claude/unicode.ts",
  `/**
 * Unicode ${u.version} tables for the Claude encodings, answered by ctok's
 * own Python predicates.
 * Auto-generated by scripts/generate-claude-encodings.ts - DO NOT EDIT
 *
${credit()} */

/** Stream class, in the low 3 bits of a fact word. */
export const CLASS = ${JSON.stringify(u.classes)} as const;

/** One bit per ctok predicate in a fact word. */
export const FLAG = ${JSON.stringify(u.flags)} as const;

/** Fact word of every BMP codepoint, as runs: [last codepoint, word, ...]. */
export const FACT_RUNS: readonly number[] = ${JSON.stringify(u.facts)};

/** Every BMP codepoint ctok lowers, but U+0130: [codepoint, lowercase, ...]. */
export const LOWER: readonly number[] = ${JSON.stringify(u.lower)};

/** Codepoints assigned in Unicode ${u.version}: [first, last, ...], inclusive. */
export const ASSIGNED: readonly number[] = ${JSON.stringify(u.assigned)};

/**
 * Canonical combining class of every codepoint with a non-zero one, as runs:
 * [first, last, class, ...], inclusive.
 */
export const CCC: readonly number[] = ${JSON.stringify(u.ccc)};
`
);

for (const enc of ENCODINGS) {
  const f = data.families[enc.ctok]!;
  const count = (n: number) => n.toLocaleString("en-US");
  await write(
    `src/encoding/${enc.name}.ts`,
    `/**
 * ${enc.name.toUpperCase()} encoding: ${enc.models}.
 * Auto-generated by scripts/generate-claude-encodings.ts - DO NOT EDIT
 *
${credit(f.family)} *
 * Pieces: ${count(f.pieces.length)}. Byte prefixes: ${count(f.bytePrefixes.length)}. Longest piece: ${f.maxPieceLength} codepoints.
 */
import { createClaudeCodec } from "../claude/codec";

export const kind = "ctok";

export const name = "${enc.name}";

export const codec = createClaudeCodec({
  name,
  foldQuotes: ${f.foldQuotes},
  allcapsMin: ${f.allcapsMin},
  frameBow: ${f.frameBow},
  tailNewlines: ${enc.tailNewlines},
  bytePrefixes: [
${f.bytePrefixes.map(literal).join(",\n")}
  ],
  pieces: [
${f.pieces.map(literal).join(",\n")}
  ],
});
`
  );
}
